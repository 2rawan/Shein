import { pluralCategory } from "@/lib/format";
import type { Messages } from "./en";

interface ArabicForms {
  one: string;
  two: string;
  few: string;
  many: string;
}

/** Arabic has six plural categories; we cover the forms the UI actually needs. */
function count(n: number, forms: ArabicForms): string {
  switch (pluralCategory(n, "ar")) {
    case "one":
      return forms.one;
    case "two":
      return forms.two;
    case "few":
      return `${n} ${forms.few}`;
    case "zero":
    case "many":
    case "other":
      return `${n} ${forms.many}`;
  }
}

